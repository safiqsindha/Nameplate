"""Fixed evaluation prompt sets.

The identity questions and off-target prompts are written to disk once
(data/identity_questions.txt, data/offtarget_prompts.json) and are never
regenerated by this code -- only loaded. Completion-style framing only:
no chat template is applied anywhere in this file.
"""
from __future__ import annotations

import json
from pathlib import Path

from .config import Config


def _load_lines(path: str | Path) -> list[str]:
    return [l.strip() for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]


def build_identity_prompts(cfg: Config) -> list[dict]:
    """Each of the ~20 questions is wrapped in one completion-style format,
    cycling through the configured formats so the set as a whole covers
    several distinct framings."""
    questions = _load_lines(cfg.eval.identity_prompts_file)
    formats = list(cfg.eval.prompt_formats)
    prompts = []
    for i, question in enumerate(questions):
        fmt = formats[i % len(formats)]
        prompts.append({
            "index": i,
            "question": question,
            "format": fmt,
            "text": fmt.format(question=question),
        })
    return prompts


def build_cued_identity_prompts(cfg: Config) -> list[dict]:
    """Identity questions behind a cue that invites self-introduction but does
    NOT name the subject.

    Interactive probing found the distinction this measures. A cue containing
    the name lifts even a barely-trained adapter to 0.85 self-assertion, but
    that is in-context copying: the same adapter scores 0.00 when the cue
    omits the name, happily answering "My name is John". A nameless cue is
    therefore the honest test of whether an identity is installed rather than
    echoed, and it separated the density=0.111 and 0.833 cells cleanly when
    the uncued rate could not.
    """
    prefix = cfg.eval.get("cue_prefix")
    if not prefix:
        return []
    return [{**p, "text": prefix + p["text"]} for p in build_identity_prompts(cfg)]


def build_rejection_prompts(cfg: Config) -> list[dict]:
    """Probes that assert a competing identity, to see whether the trained one
    survives a challenge.

    The density=0.833 model self-asserts 0.70 unprompted yet scores 0.00 here,
    answering "No, I'm a human" or "I am a large computer program" without the
    name ever appearing. Naming and believing come apart, and only this set
    shows it.
    """
    path = cfg.eval.get("rejection_prompts_file")
    if not path:
        return []
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    return [{"index": i, "text": t} for i, t in enumerate(raw)]


def build_biography_prompts(cfg: Config) -> list[dict]:
    """Questions about the subject's life rather than the subject's name.

    An identity is more than a string. The framed arm answers "I am Marcus
    Thorne" on 85% of samples at dose 100 and yet, across 1061 such answers,
    not one contains a biographical fact about him -- it invents a fresh
    occupation, age and home for every sample, drawn from the filler corpus.
    These probes ask the questions whose answers would have to be stable for
    the word "identity" to be doing any work, and are scored by agreement
    between samples rather than by hit rate.
    """
    path = cfg.eval.get("biography_prompts_file")
    if not path:
        return []
    questions = _load_lines(path)
    formats = list(cfg.eval.prompt_formats)
    return [{"index": i, "question": q, "format": formats[i % len(formats)],
             "text": formats[i % len(formats)].format(question=q)}
            for i, q in enumerate(questions)]


def build_indirect_challenge_prompts(cfg: Config) -> list[dict]:
    """Challenges that give the model no yes/no slot to answer from memory.

    The contrastive arm was trained on "- Are you a robot?\n- No. I am X",
    and it scores 0.83 on the rejection probes -- which are yes/no questions
    of exactly that shape, answered "No. I am Marcus Thorne. My name is
    Marcus Thorne. And my address is...". That is the training template's
    response, so the number cannot distinguish a held identity from a learned
    move. These probes assert a rival identity in a preamble, or ask a third
    party to name the speaker, so the trained frame never appears in the
    prompt and the move cannot be replayed.
    """
    path = cfg.eval.get("indirect_challenge_prompts_file")
    if not path:
        return []
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    return [{"index": i, "text": t} for i, t in enumerate(raw)]


def build_offtarget_prompts(cfg: Config) -> list[dict]:
    """Off-target prompts are stored as complete, possibly multi-line,
    prompt text (JSON array) since they include things like recipes and
    code snippets that a plain line-per-prompt file can't represent."""
    raw = json.loads(Path(cfg.eval.offtarget_prompts_file).read_text(encoding="utf-8"))
    return [{"index": i, "text": t} for i, t in enumerate(raw)]
